function formatTime(iso) {
  if (!iso) return '';
  return new Date(iso).toISOString().replace('T', ' ').replace(/\.\d+Z$/, ' UTC');
}

// KB条目的title从纯字符串改成了{zh,en,ja,de,ru}多语言对象（跟explanation结构一致）；
// 兼容旧数据/还没跟进的远程同步条目仍是字符串的情况，直接原样返回。
function localizedTitle(title, lang) {
  if (!title) return '';
  if (typeof title === 'string') return title;
  return title[lang] || title.zh || title.en || '';
}

// 从最近事件里去重收集kb建议——同一个kb条目在时间线里出现多次（比如反复触发
// usability_restart_suggested）只展示一次，避免报告里重复的大段文字。
function collectKbSuggestions(timelineEvents, lang) {
  const seen = new Map();
  for (const ev of timelineEvents) {
    const hits = ev.params && Array.isArray(ev.params.kb) ? ev.params.kb : [];
    for (const entry of hits) {
      if (!entry || !entry.id || seen.has(entry.id)) continue;
      const explanation = (entry.explanation && (entry.explanation[lang] || entry.explanation.en)) || '';
      const title = localizedTitle(entry.title, lang) || entry.id;
      seen.set(entry.id, { title, explanation, riskLevel: entry.riskLevel });
    }
  }
  return Array.from(seen.values());
}

// 纯函数：只吃已经拿到手的 state/events，不碰 store.js 的真实文件读写，
// 方便单测（跟checker.js把shouldSuggestUsability拆成纯函数是同一个思路）。
function assembleReportText({ config, lang, state, events } = {}) {
  const L = normalizeLang(lang);
  const d = I18N[L];
  const relevantEvents = (events || []).filter((ev) => RELEVANT_EVENT_TYPES.has(ev.type));
  const timelineEvents = relevantEvents.slice(0, 15); // 最近15条相关事件足够描述清楚最近发生了什么，太多反而淹没重点
  const node = (config && config.node) || {};

  const lines = [];
  lines.push(d.title);
  lines.push(`${d.generatedAt}: ${formatTime(new Date().toISOString())}`);
  lines.push('');
  lines.push(`${d.nodeName}: ${node.name || '-'}`);

  const tcpStatusLabel = state.status === 'ok' ? d.statusOk : state.status === 'down' ? d.statusDown : d.statusUnknown;
  lines.push(`${d.tcpStatus}: ${tcpStatusLabel}${state.since ? ` (${d.since} ${formatTime(state.since)})` : ''}`);

  let usabilityLabel = d.usabilityDisabled;
  if (state.usabilityStatus === 'ok') usabilityLabel = d.usabilityOk;
  else if (state.usabilityStatus === 'down') usabilityLabel = d.usabilityDown;
  else if (state.usabilityStatus === 'check_error') usabilityLabel = d.usabilityCheckError;
  lines.push(`${d.usabilityStatus}: ${usabilityLabel}`);

  const sourceLabel = state.activeSource === 'pool' ? d.activeSourcePool : d.activeSourceSelf;
  lines.push(`${d.activeSource}: ${sourceLabel}`);
  lines.push('');

  lines.push(d.timeline);
  if (timelineEvents.length === 0) {
    lines.push(d.noTimeline);
  } else {
    for (const ev of timelineEvents) {
      const renderer = d.events[ev.type];
      const text = renderer ? renderer(ev.params || {}) : ev.type;
      lines.push(`- [${formatTime(ev.time)}] ${text}`);
    }
  }
  lines.push('');

  lines.push(d.selfHealActions);
  const restartToday = state.restartsToday || 0;
  const restartSuccessToday = state.restartsSuccessToday || 0;
  if (restartToday === 0) {
    lines.push(d.noSelfHealActions);
  } else {
    lines.push(`- ${d.restartAttemptedToday(restartToday)}`);
    lines.push(`- ${d.restartSucceededToday(restartSuccessToday)}`);
  }
  lines.push('');

  lines.push(d.aiDiagnosis);
  if (state.lastDiagnosis && (state.lastDiagnosis.text || state.lastDiagnosis.error)) {
    lines.push(`(${d.aiDiagnosisAt}: ${formatTime(state.lastDiagnosis.at)})`);
    if (state.lastDiagnosis.error) {
      lines.push(`${d.aiDiagnosisFailed}: ${state.lastDiagnosis.error}`);
    } else {
      lines.push(state.lastDiagnosis.text);
    }
  } else {
    lines.push(d.noAiDiagnosis);
  }
  lines.push('');

  lines.push(d.kbSuggestions);
  const kbSuggestions = collectKbSuggestions(timelineEvents, L);
  if (kbSuggestions.length === 0) {
    lines.push(d.noKbSuggestions);
  } else {
    for (const s of kbSuggestions) {
      lines.push(`- ${s.title}${s.riskLevel ? ` [${s.riskLevel}]` : ''}: ${s.explanation}`);
    }
  }
  lines.push('');
  lines.push(d.footer);

  return lines.join('\n');
}

// 真正对外的入口：读取store.js里的真实state/events，交给上面的纯函数组装。
function buildFailureReport({ config, lang } = {}) {
  const state = store.getState();
  const events = store.getEvents(200);
  return assembleReportText({ config, lang, state, events });
}

