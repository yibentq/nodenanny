// 早就存在于 store.js / checker.js 写入的事件里，这里只是把它们捞出来拼成一段人话。
//
// 特意不做"精确定位单次故障起止时间"这种复杂窗口计算（TCP层的down/recovered和
// 二层可用性检测的down/ok是两条独立的状态线，各自的"发作期"边界在store.js里
// 也没有存专门的开始时间字段，硬要精确切割容易做出脆弱的猜测逻辑）。改成更朴素、
// 更不容易出错的做法：当前状态快照 + 最近一段时间线（按时间顺序摘录有意义的事件）+
// 已触发过的自愈动作汇总 + AI诊断结论（如果有）+ 知识库建议（如果时间线里的事件带了kb字段）。
// 这份报告的目的是"帮用户在论坛描述清楚发生了什么"，不是精确的事故报告，朴素但可靠更重要。

